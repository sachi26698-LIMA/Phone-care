#!/usr/bin/env bash
# Reproducible debug build for a machine that has the Android toolchain.
#
# Checks every prerequisite first and fails with an explicit message instead of
# a Gradle stack trace. Nothing is downloaded silently.
#
# Usage:
#   ./build-local.sh              # assembleDebug, prints APK path + sha256
#   ./build-local.sh install      # assembleDebug then adb install -r
#
# Prerequisites:
#   * JDK 17+               (java -version)
#   * Android SDK           (ANDROID_HOME or ANDROID_SDK_ROOT)
#       platforms/android-35
#       build-tools/35.0.0      (aapt2, d8, apksigner, zipalign)
#       platform-tools          (adb)
#   * Gradle 8.9+           (or the wrapper generated by `gradle wrapper`)

set -euo pipefail
cd "$(dirname "$0")"

fail() {
  echo "error: $1" >&2
  shift
  for line in "$@"; do echo "  - $line" >&2; done
  exit 1
}

command -v java >/dev/null 2>&1 || fail "java not found on PATH" \
  "Install JDK 17 (Temurin, Zulu, or the JDK bundled with Android Studio)" \
  "Then: export JAVA_HOME=/path/to/jdk"

JAVA_MAJOR="$(java -version 2>&1 | sed -n 's/.*version "\([0-9]*\).*/\1/p' | head -1)"
[ -n "${JAVA_MAJOR:-}" ] || fail "could not determine the Java version" "Run java -version and check the output"
[ "$JAVA_MAJOR" -ge 17 ] || fail "JDK 17+ required (found $JAVA_MAJOR)" "AGP 8.7 needs JDK 17 or newer"

SDK="${ANDROID_HOME:-${ANDROID_SDK_ROOT:-}}"
[ -n "$SDK" ] || fail "ANDROID_HOME / ANDROID_SDK_ROOT is not set" \
  "Install the Android SDK (Android Studio → SDK Manager, or command-line tools)" \
  "Then: export ANDROID_HOME=\$HOME/Android/Sdk"

[ -d "$SDK/platforms/android-35" ] || fail "platform android-35 is missing" \
  "sdkmanager \"platforms;android-35\""
[ -d "$SDK/build-tools/35.0.0" ] || fail "build-tools 35.0.0 is missing" \
  "sdkmanager \"build-tools;35.0.0\""

if [ ! -x ./gradlew ]; then
  command -v gradle >/dev/null 2>&1 || fail "no Gradle wrapper and no gradle on PATH" \
    "Either install Gradle 8.9+ and run 'gradle wrapper --gradle-version 8.9'" \
    "or open native/android in Android Studio once (it generates the wrapper)"
  echo "Generating the Gradle wrapper…"
  gradle wrapper --gradle-version 8.9 --distribution-type bin
fi

echo "Building debug APK…"
./gradlew --no-daemon assembleDebug

APK="app/build/outputs/apk/debug/app-debug.apk"
[ -f "$APK" ] || fail "build finished but $APK is missing" "Inspect app/build/outputs/apk/debug/"

echo
echo "APK:    $(pwd)/$APK"
echo "SHA256: $(sha256sum "$APK" | cut -d' ' -f1)"
echo "Size:   $(du -h "$APK" | cut -f1)"
echo
"$SDK/build-tools/35.0.0/aapt2" dump badging "$APK" | head -8 || true

if [ "${1:-}" = "install" ]; then
  command -v adb >/dev/null 2>&1 || fail "adb not found" "Add \$ANDROID_HOME/platform-tools to PATH"
  echo "Installing on the connected device…"
  adb install -r "$APK"
  echo "Launch with: adb shell am start -n app.phonecare.diagnostics/.MainActivity"
fi
